/* eslint-disable eslint/no-await-in-loop -- ExifTool shares one Perl interpreter, so calls must be sequential */
/* oxlint-disable react-doctor/async-await-in-loop -- the real engine cannot run concurrent calls */
import { createHash } from "node:crypto";
// Add the fixed cleanable property groups with the same pinned engine as the app.
import { readFileSync, writeFileSync } from "node:fs";

import { writeMetadata } from "@colorhythm/exiftool-wasm";

const directory = new URL(
  "../../src/features/expose/fixtures/",
  import.meta.url
);
for (const format of ["mp4", "mov", "m4v", "m4a"]) {
  const path = new URL(`metadata.${format}`, directory);
  const result = await writeMetadata(
    { data: new Uint8Array(readFileSync(path)), name: `source.${format}` },
    {
      "Keys:GPSCoordinates": "+40.736435-073.993160+174/",
      "Keys:Make": "Fixture make",
      "Keys:Model": "Fixture model",
      "Keys:CreationDate": "2020:01:02 03:04:05Z",
      "ItemList:Artist": "Fixture author",
      "Keys:Software": "Fixture software",
      "ItemList:Title": "Fixture title",
      "ItemList:Comment": "Fixture comment",
    },
    { args: ["-m", "-q"] }
  );
  if (!result.success) {
    throw new Error(result.error);
  }
  writeFileSync(path, new Uint8Array(result.data));
}
const manifest = JSON.parse(
  readFileSync(new URL("FILES.json", directory), "utf-8")
);
for (const line of manifest) {
  const data = readFileSync(new URL(line.file, directory));
  line.bytes = data.length;
  line.sha256 = createHash("sha256").update(data).digest("hex");
  line.source =
    "Generated by generate.py, then tag-media.mjs; no remote inputs";
}
writeFileSync(
  new URL("FILES.json", directory),
  `${JSON.stringify(manifest, null, 2)}\n`
);
