/**
 * Copies the PDF reader assets and the exact third-party notices that the
 * PDF engine serves. Large files stay out of the repository and out of the
 * Workbox precache; the service worker caches `/folio/` at runtime.
 *
 * Runs before `dev`, `build`, and `build:worker`. A matching version marker
 * keeps a repeated run cheap.
 */

import {
  cp,
  mkdir,
  readFile,
  readdir,
  copyFile,
  writeFile,
} from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const app = path.resolve(import.meta.dirname, "..");
const target = path.join(app, "public/folio");
const notices = path.join(target, "notices");
const versionOf = async (name: string) => {
  const manifest = require.resolve(`${name}/package.json`);
  const parsed = JSON.parse(await readFile(manifest, "utf-8")) as {
    version: string;
  };
  return { version: parsed.version, directory: path.dirname(manifest) };
};
const pdfjs = await versionOf("pdfjs-dist");
const pdfLib = await versionOf("pdf-lib");
const markerVersion = `pdfjs-${pdfjs.version}-pdf-lib-${pdfLib.version}`;
const marker = path.join(target, ".version");
try {
  if ((await readFile(marker, "utf-8")).trim() === markerVersion) {
    process.exit(0);
  }
} catch {
  // First run.
}

await mkdir(notices, { recursive: true });
for (const name of ["cmaps", "standard_fonts", "wasm"]) {
  await cp(path.join(pdfjs.directory, name), path.join(target, name), {
    recursive: true,
    force: true,
  });
}
const copies: [string, string][] = [
  [path.join(pdfjs.directory, "LICENSE"), "PDFJS-APACHE-2.0.txt"],
  [path.join(pdfjs.directory, "cmaps/LICENSE"), "PDFJS-CMAPS.txt"],
  [
    path.join(pdfjs.directory, "standard_fonts/LICENSE_FOXIT"),
    "PDFJS-STANDARD-FONTS-FOXIT.txt",
  ],
  [
    path.join(pdfjs.directory, "standard_fonts/LICENSE_LIBERATION"),
    "PDFJS-STANDARD-FONTS-LIBERATION.txt",
  ],
  [path.join(pdfLib.directory, "LICENSE.md"), "PDFLIB-MIT.txt"],
];
for (const license of await readdir(path.join(pdfjs.directory, "wasm"))) {
  if (license.startsWith("LICENSE")) {
    copies.push([
      path.join(pdfjs.directory, "wasm", license),
      `PDFJS-${license}`,
    ]);
  }
}
for (const dependency of [
  "@pdf-lib/standard-fonts",
  "@pdf-lib/upng",
  "pako",
  "tslib",
]) {
  const resolved = await versionOf(dependency).catch(() => null);
  if (!resolved) {
    continue;
  }
  for (const file of await readdir(resolved.directory)) {
    if (/^LICENSE/iu.test(file)) {
      copies.push([
        path.join(resolved.directory, file),
        `${dependency.replaceAll("/", "-").replaceAll("@", "")}-${file}`,
      ]);
    }
  }
}
for (const [from, to] of copies) {
  await copyFile(from, path.join(notices, to));
}
await writeFile(marker, `${markerVersion}\n`);
await writeFile(
  path.join(notices, "VERSIONS.txt"),
  [
    `pdfjs-dist ${pdfjs.version}`,
    `pdf-lib ${pdfLib.version}`,
    "Source: the exact npm tarballs for these pins.",
    "Generated by apps/web/scripts/copy-folio-assets.ts.",
    "",
  ].join("\n")
);
console.log(`PDF engine assets copied for ${markerVersion}.`);
