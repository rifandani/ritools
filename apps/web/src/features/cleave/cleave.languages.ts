const byAlias = new Map<string, Language>(
  LANGUAGE_CATALOG.flatMap(({ id, aliases }) =>
    [id, ...aliases].map((alias): [string, Language] => [alias, id])
  )
);

export const canonicalLanguage = (value: string): Language | undefined =>
  byAlias.get(value.toLowerCase());

const byId = new Map<string, string>(
  LANGUAGE_CATALOG.map((item) => [item.id, item.name])
);
export const languageLabel = (language: string) =>
  byId.get(language) ?? language;
