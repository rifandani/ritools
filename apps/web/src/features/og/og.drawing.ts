/**
 * The Open Graph card: one for the site, one for each Tool.
 *
 * A card is a printed sheet: a red ground, the wordmark, a slash bar, and the
 * words of the product. Every letter is an outline from the glyph atlas, so
 * the sheet is a vector before it is a raster, and the same code draws it on a
 * Node server and on a Worker.
 */

import { PALETTE, round, slashBar, svgDocument } from "@/core/libs/brand/svg";
import messages from "@/core/libs/i18n/locales/en-US";
import { TOOLS } from "@/features/tools/tools";

import { FACE_OF, fitText, layoutText, wrapText } from "./og.atlas";
import type { TextRun } from "./og.atlas";
import { OG_SIZE } from "./og.params";
import type { OgCard, ToolPath } from "./og.params";
import { buildWordmark } from "./og.wordmark";
import type { CardWordmark } from "./og.wordmark";

/** The line that rides in every card this endpoint draws. */
export const ORIGIN = {
  site: "Generated by GET /api/og in apps/web/src/features/og. The Ritools Open Graph card: the ransom wordmark and the letterforms of Anton and Archivo (SIL OFL, self-hosted), set from the glyph atlas.",
  tool: "Generated by GET /api/og?tool=<path> in apps/web/src/features/og. The Open Graph card of one Tool: the ransom wordmark and the letterforms of Anton and Archivo (SIL OFL, self-hosted), set from the glyph atlas.",
} as const;

/** The rules of the card: the frame of the sheet and the marks on it. */
const DRAWING_RULES = {
  /** The margin of the sheet. */
  margin: 72,
  /** The weight of a rule on the card. */
  rule: 3,
} as const;

/** One drawn card, and the line that says where it came from. */
export interface CardDrawing {
  svg: string;
  width: number;
  height: number;
  origin: string;
}

/** The name of one Tool and its promise, in the language the site ships first. */
const toolCopy = (path: ToolPath) => {
  const tool = TOOLS.find((entry) => entry.path === path);
  if (!tool) {
    return null;
  }
  // A Tool promise is one plain message: `promiseKey` is a literal of the
  // catalog, so the catalog gives the string, never a plural entry.
  return { name: tool.name, promise: messages[tool.promiseKey] };
};

/** The wordmark, placed on the sheet. The card only scales it. */
const placeWordmark = (
  wordmark: CardWordmark,
  x: number,
  y: number,
  width: number
) => {
  const scale = width / wordmark.width;
  return {
    height: wordmark.height * scale,
    markup: `<g transform="translate(${round(x)} ${round(y)}) scale(${round(scale)})">${wordmark.content}</g>`,
  };
};

/** One line of the card, placed. The ink of the sheet is the line's ink. */
const placeLine = (run: TextRun, x: number, y: number) =>
  `<g transform="translate(${round(x)} ${round(y)})" fill="${PALETTE.paper}">${run.content}</g>`;

/** The site card: the wordmark, the promise, and the stamp. */
export const buildSiteDrawing = (): CardDrawing => {
  const { height, width } = OG_SIZE;
  const { margin } = DRAWING_RULES;
  const wordmark = buildWordmark("Ritools", "red");
  const placed = placeWordmark(wordmark, margin, margin - 12, 600);

  const plateWidth = 400;
  const plateInnerWidth = plateWidth - 52;
  const deck = layoutText("SMALL UTILITIES THAT RUN", FACE_OF.poster, 50, 0.01);
  const deckTwo = layoutText(
    "ENTIRELY ON YOUR DEVICE.",
    FACE_OF.poster,
    50,
    0.01
  );
  const kicker = layoutText("LOCAL ONLY", FACE_OF.poster, 34, 0.01);
  const promiseOne = fitText(
    "NO ACCOUNT. NO UPLOAD.",
    FACE_OF.label,
    21,
    0.08,
    plateInnerWidth
  );
  const promiseTwo = fitText(
    "NO SERVER STORAGE.",
    FACE_OF.label,
    21,
    0.08,
    plateInnerWidth
  );
  const promiseThree = fitText(
    "THE ONLY CAP IS YOUR DEVICE.",
    FACE_OF.label,
    21,
    0.08,
    plateInnerWidth
  );

  const plateX = width - margin - plateWidth;
  const plateY = height - margin - 186;
  const plateInner = plateX + 26;

  const body = [
    placed.markup,
    `<path d="${slashBar(margin, margin + placed.height + 48, 176, 12)}" fill="${PALETTE.paper}"/>`,
    placeLine(deck, margin, margin + placed.height + 164),
    placeLine(deckTwo, margin, margin + placed.height + 226),
    `<rect x="${plateX}" y="${plateY}" width="${plateWidth}" height="186" fill="none" stroke="${PALETTE.paper}" stroke-width="${DRAWING_RULES.rule}"/>`,
    placeLine(kicker, plateInner, plateY + 58),
    `<rect x="${plateInner}" y="${plateY + 80}" width="${plateInnerWidth}" height="2" fill="${PALETTE.paper}"/>`,
    placeLine(promiseOne, plateInner, plateY + 118),
    placeLine(promiseTwo, plateInner, plateY + 148),
    placeLine(promiseThree, plateInner, plateY + 178),
  ].join("");

  return {
    height,
    origin: ORIGIN.site,
    svg: svgDocument({ background: PALETTE.red, body, height, width }),
    width,
  };
};

/** The card of one Tool: its name in ransom letters, and its promise. */
export const buildToolDrawing = (
  name: string,
  tagline: string
): CardDrawing => {
  const { height, width } = OG_SIZE;
  const { margin } = DRAWING_RULES;
  const wordmark = buildWordmark("Ritools", "red");
  const placed = placeWordmark(wordmark, margin, margin - 20, 320);

  const tool = buildWordmark(name, "red");
  const toolScale = (width - margin * 2) / tool.width;
  const toolHeight = tool.height * toolScale;
  const toolY = margin + placed.height + 26;

  const lines = wrapText(
    tagline.toUpperCase(),
    FACE_OF.poster,
    38,
    0.01,
    width - margin * 2
  );
  const promise = layoutText(
    "NO ACCOUNT. NO UPLOAD. NO SERVER STORAGE. THE ONLY CAP IS YOUR DEVICE.",
    FACE_OF.label,
    21,
    0.08
  );

  const body = [
    placed.markup,
    `<g transform="translate(${round(margin)} ${round(toolY)}) scale(${round(toolScale)})">${tool.content}</g>`,
    `<path d="${slashBar(margin, toolY + toolHeight + 34, 176, 12)}" fill="${PALETTE.paper}"/>`,
    ...lines.map((line, index) =>
      placeLine(line, margin, toolY + toolHeight + 106 + index * 46)
    ),
    placeLine(promise, margin, height - margin - 6),
  ].join("");

  return {
    height,
    origin: ORIGIN.tool,
    svg: svgDocument({ background: PALETTE.red, body, height, width }),
    width,
  };
};

/** The card for one request. A Tool the catalog does not know is the site. */
export const cardDrawing = (card: OgCard): CardDrawing => {
  if (card.kind === "tool") {
    const copy = toolCopy(card.path);
    if (copy) {
      return buildToolDrawing(copy.name, copy.promise);
    }
  }
  return buildSiteDrawing();
};
